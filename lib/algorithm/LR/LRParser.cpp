module LRParser;
import std;
import constants;

LRParser::LRParser(AST::Tree* t, std::size_t lookahead_k, bool build_immediately) : tree(t), k(lookahead_k) {
    if (k == 0) throw std::invalid_argument("LRParser: k must be >= 1");
    if (!tree) throw std::invalid_argument("LRParser: null grammar tree");
    if (build_immediately) build();
}
LRParser::LRParser(AST::Tree* t, std::size_t k, std::string_view cache) : LRParser(t, k, false) {
    loadCache(cache);
    build();
}
LRParser::LRParser(AST::Tree& t, std::size_t k) : LRParser(&t, k, true) {}

std::string LRParser::formatName(const Name& name) {
    std::string out;
    for (const auto& part : name) {
        if (!out.empty()) out += "::";
        out += part;
    }
    return out;
}

std::string LRParser::formatSequence(const Lookahead& sequence) {
    std::string str;
    for (const auto& token : sequence) {
        if (!str.empty()) str += " ";
        str += formatName(token);
    }
    return str;
}

std::string LRParser::ActionTypeToString(Action_type type) {
    switch (type) {
        case Action_type::SHIFT: return "SHIFT";
        case Action_type::REDUCE: return "REDUCE";
        case Action_type::ACCEPT: return "ACCEPT";
        case Action_type::DFA_RESOLVE: return "DFA_RESOLVE";
        case Action_type::ERR: return "ERROR";
    }
    throw std::logic_error("Unknown LR action type");
}

bool LRParser::looksLikeTerminal(const Name& name) {
    if (name.empty()) return false;
    for (unsigned char ch : name.back()) {
        if (std::isalpha(ch)) return std::isupper(ch) != 0;
    }
    return false;
}

bool LRParser::isNonterminal(const Name& name) const {
    return productions_by_lhs.contains(name);
}

void LRParser::prepareProductions() {
    auto rejectCounters = [&](auto&& self, const AST::RuleMember& member) -> void {
        for (const auto& feature : member.features)
            if (std::holds_alternative<AST::Counter>(feature) || std::holds_alternative<AST::SharedCounterRegistration>(feature))
                throw std::invalid_argument(member.position.file + ":" + std::to_string(member.position.line) +
                    ": counted repetitions require the LL algorithm");
        if (member.isGroup()) for (const auto& child : member.getGroup().values) self(self, *child);
        if (member.isOp()) for (const auto& child : member.getOp().options) self(self, *child);
    };
    for (const auto& [name, rule] : tree->getTreeMap()) {
        if (rule.external) throw std::invalid_argument("External parser calls currently require the LL algorithm");
        for (const auto& member : rule.rule_members) rejectCounters(rejectCounters, *member);
    }
    productions.clear();
    productions_by_lhs.clear();
    rules.clear();
    first_k.clear();
    auto& grammar = tree->getInitialItemSet();
    const Name main{"main"};
    if (!grammar.contains(main) || grammar.at(main).empty())
        throw std::invalid_argument("LRParser: grammar must define non-empty rule 'main'");
    if (grammar.contains(augmented))
        throw std::invalid_argument("LRParser: reserved rule name __ispa_lr_augmented");

    // Synthetic production 0: __ispa_lr_augmented -> main.
    Production start;
    start.lhs = augmented;
    start.rhs.push_back(main);
    productions.push_back(std::move(start));
    productions_by_lhs[augmented].push_back(0);

    // Sort by qualified rule name, retain each rule's original alternative order.
    // This makes production and state numbering reproducible across builds.
    std::map<Name, const stdu::vector<AST::Rule>*> ordered;
    for (const auto& [lhs, alternatives] : grammar) {
        if (lhs.empty() || lhs.back().empty())
            throw std::invalid_argument("LRParser: empty production name");
        // The tree can also hold lexer rule definitions. Only parser rule
        // definitions are LR nonterminals; uppercase names denote tokens.
        if (looksLikeTerminal(lhs)) continue;
        ordered.emplace(lhs, &alternatives);
    }
    // The AST normalizer expands inserted __WS? into nullable helper rules.
    // They describe trivia boundaries, not alternatives in the LR language.
    std::set<Name> whitespace_helpers;
    bool explicit_whitespace = false;
    for (const auto& [lhs, alternatives] : ordered) {
        bool has_inserted_space = false, only_space = true;
        for (const auto& alternative : *alternatives) {
            for (const auto& member : alternative.rule_members) {
                const bool space = member && member->isName() &&
                    member->getName().name == constants::whitespace;
                if (space && !member->isAutoGenerated) explicit_whitespace = true;
                if (!space || !member->isAutoGenerated) only_space = false;
                else has_inserted_space = true;
            }
        }
        if (only_space && has_inserted_space) whitespace_helpers.insert(lhs);
    }
    // Explicit references to the reserved whitespace token keep ordinary CFG
    // semantics; only injected whitespace is eligible for trivia treatment.
    skip_automatic_whitespace = !explicit_whitespace && !whitespace_helpers.empty();
    for (const auto& [lhs, alternatives] : ordered) {
        if (skip_automatic_whitespace && whitespace_helpers.contains(lhs)) continue;
        for (const auto& original : *alternatives) {
            Production p;
            p.lhs = lhs;
            p.source = original;
            p.source.rule_members.clear();
            p.whitespace_gaps.push_back(false);
            std::size_t member_index = 0;
            for (const auto& member : original.rule_members) {
                const bool trivia = skip_automatic_whitespace && member && member->isName() &&
                    (whitespace_helpers.contains(member->getName().name) ||
                     (member->isAutoGenerated && member->getName().name == constants::whitespace));
                if (trivia) { p.whitespace_gaps.back() = true; continue; }
                ++member_index;
                if (!member || !member->isName() || member->quantifier != '\0')
                    throw std::invalid_argument(
                        "LRParser: unnormalized member in " + formatName(lhs) +
                        "; lower groups, alternatives and quantifiers to named productions first");
                p.rhs.push_back(member->getName().name);
                p.source.rule_members.push_back(member);
                p.source_members.push_back(member_index);
                p.whitespace_gaps.push_back(false);
                if (p.rhs.back().empty())
                    throw std::invalid_argument("LRParser: empty symbol in " + formatName(lhs));
            }
            // The normalizer builds repetitions right-recursively (T -> payload T), which LL needs. For LR that costs a stack
            // entry per element and a rebuilt capture list per reduction (quadratic). Rotate the recursive production to
            // T -> T payload: constant stack depth, and the reduction appends to the list it already owns.
            if (lhs.back() == "__tail" && p.rhs.size() >= 2 && p.rhs.back() == lhs) {
                std::rotate(p.rhs.rbegin(), p.rhs.rbegin() + 1, p.rhs.rend());
                std::rotate(p.source.rule_members.rbegin(), p.source.rule_members.rbegin() + 1, p.source.rule_members.rend());
                std::rotate(p.source_members.rbegin(), p.source_members.rbegin() + 1, p.source_members.rend());
                // Gap flags: g[i] precedes member i, g[n] follows the last. New order T p1..pk keeps the gap before the payload
                // between T and p1; the old gaps around the former tail (after pk, after T) now both follow pk.
                auto& g = p.whitespace_gaps;
                const std::size_t n = p.rhs.size();
                std::vector<bool> h(n + 1, false);
                h[1] = g[0];
                for (std::size_t i = 1; i + 1 < n; ++i) h[i + 1] = g[i];
                h[n] = g[n - 1] || g[n];
                g = std::move(h);
            }
            const auto id = productions.size();
            productions_by_lhs[lhs].push_back(id);
            rules.push_back({lhs, {p.rhs.size(), p.source.rule_members}});
            productions.push_back(std::move(p));
        }
    }
    for (const auto& p : productions) {
        for (const auto& symbol : p.rhs) {
            // The parser must not silently treat an undefined *parser* symbol
            // as a token. Uppercase symbol names are lexer terminals.
            if (!isNonterminal(symbol) &&
                !looksLikeTerminal(symbol))
                throw std::invalid_argument("LRParser: unresolved nonterminal " + formatName(symbol));
            if (symbol == eof)
                throw std::invalid_argument("LRParser: '$' is reserved for end of input");
        }
    }
}

LRParser::Lookaheads LRParser::concatenate(
    const Lookaheads& left, const Lookaheads& right) const {
    Lookaheads result;
    for (const auto& a : left) {
        for (const auto& b : right) {
            Lookahead combined = a;
            if (combined.size() < k) {
                const auto count = std::min(k - combined.size(), b.size());
                combined.insert(combined.end(), b.begin(), b.begin() + count);
            }
            result.insert(std::move(combined));
        }
    }
    return result;
}

void LRParser::computeFirstK() {
    // Least fixed point of FIRST_k for the same normalized productions
    // used to build the LR automaton. Empty token sequence denotes epsilon.
    first_k.clear();
    for (const auto& p : productions) first_k[p.lhs];
    bool changed = true;
    while (changed) {
        changed = false;
        for (const auto& p : productions) {
            Lookaheads seq_first{Lookahead{}}; // FIRST_k(epsilon)
            for (const auto& symbol : p.rhs) {
                if (isNonterminal(symbol))
                    seq_first = concatenate(seq_first, first_k.at(symbol));
                else
                    seq_first = concatenate(seq_first, Lookaheads{Lookahead{symbol}});
                if (seq_first.empty()) break;
            }
            auto& target = first_k[p.lhs];
            const auto previous = target.size();
            target.insert(seq_first.begin(), seq_first.end());
            if (target.size() != previous) changed = true;
        }
    }
}

LRParser::Lookaheads LRParser::firstOfSuffix(
    const Production& p, std::size_t begin, const Lookahead& trailing,
    const Name* prepend) const {
    Lookaheads result{Lookahead{}};
    if (prepend) result = concatenate(result, Lookaheads{Lookahead{*prepend}});
    for (std::size_t i = begin; i < p.rhs.size(); ++i) {
        const auto& symbol = p.rhs[i];
        if (isNonterminal(symbol))
            result = concatenate(result, first_k.at(symbol));
        else
            result = concatenate(result, Lookaheads{Lookahead{symbol}});
        if (result.empty()) break;
    }
    return concatenate(result, Lookaheads{trailing});
}

LRParser::CanonicalItem LRParser::closureUncached(CanonicalItem items) const {
    bool changed = true;
    while (changed) {
        changed = false;
        for (auto it = items.begin(); it != items.end(); ++it) {
            const auto [production_id, dot] = it->first;
            const auto& p = productions.at(production_id);
            if (dot >= p.rhs.size()) continue;
            const auto& next = p.rhs[dot];
            const auto expanded = productions_by_lhs.find(next);
            if (expanded == productions_by_lhs.end()) continue;
            // Snapshot lookaheads, since insertions can add lookaheads to items.
            const auto current_lookaheads = it->second;
            Lookaheads next_lookaheads;
            for (const auto& lookahead : current_lookaheads) {
                auto first_set = firstOfSuffix(p, dot + 1, lookahead);
                next_lookaheads.insert(first_set.begin(), first_set.end());
            }
            for (const auto child_id : expanded->second) {
                auto& target = items[LR0Core{child_id, 0}];
                const auto previous_size = target.size();
                target.insert(next_lookaheads.begin(), next_lookaheads.end());
                if (target.size() != previous_size) changed = true;
            }
        }
    }
    return items;
}

LRParser::CanonicalItem LRParser::goTo(const CanonicalItem& items, const Name& symbol) const {
    CanonicalItem kernel;
    for (const auto& [core, lookaheads] : items) {
        const auto& rhs = productions[core.production].rhs;
        if (core.dot_pos >= rhs.size() || rhs[core.dot_pos] != symbol) continue;
        auto& target = kernel[LR0Core{core.production, core.dot_pos + 1}];
        target.insert(lookaheads.begin(), lookaheads.end());
    }
    return kernel.empty() ? CanonicalItem{} : closure(std::move(kernel));
}

void LRParser::buildCanonical() {
    action_table.clear();
    k_action_table.clear();
    goto_table.clear();
    canonical_item_set.clear();
    transitions.clear();
    conflicts.clear();
    prepareProductions();
    prepareCacheKeys();
    current_closures.clear();
    current_rows.clear();
    dependency_stamps.clear();
    cache_stats = {};
    computeFirstK();

    CanonicalItem initial;
    initial[LR0Core{0, 0}].insert(Lookahead(k, eof));
    initial = closure(std::move(initial));
    canonical_item_set.push_back(initial);
    transitions.emplace_back();
    std::map<CanonicalItem, std::size_t> indexed;
    indexed.emplace(initial, 0);

    // BFS: expanding a single state exactly once, even on a recursive grammar.
    for (std::size_t state = 0; state < canonical_item_set.size(); ++state) {
        // Copy: appending states can reallocate canonical_item_set.
        const auto current = canonical_item_set[state];
        std::set<Name> next_symbols;
        for (const auto& [core, unused] : current) {
            const auto& rhs = productions[core.production].rhs;
            if (core.dot_pos < rhs.size()) next_symbols.insert(rhs[core.dot_pos]);
        }
        for (const auto& symbol : next_symbols) {
            auto next = goTo(current, symbol);
            if (next.empty()) continue;
            auto found = indexed.find(next);
            std::size_t target = 0;
            if (found == indexed.end()) {
                target = canonical_item_set.size();
                indexed.emplace(next, target);
                canonical_item_set.push_back(std::move(next));
                transitions.emplace_back();
            } else {
                target = found->second;
            }
            transitions[state][symbol] = target;
        }
    }
}

void LRParser::buildTables() {
    auto_conflicts = false;
    resolutions.clear();
    decision_k = k;
    action_table.clear();
    k_action_table.clear();
    goto_table.clear();
    conflicts.clear();
    state_keys.clear();
    state_ids.clear();
    for (const auto& items : canonical_item_set) {
        auto key = itemKey(items);
        state_ids.emplace(key, state_keys.size());
        state_keys.push_back(std::move(key));
    }
    using Cell = std::pair<std::size_t, Lookahead>;
    std::map<Cell, std::vector<Action>> proposals;
    std::map<Cell, std::vector<ConflictOrigin>> origins;
    auto propose = [&](std::size_t state, const Lookahead& window, Action action, const LR0Core& core) {
        auto& actions = proposals[{state, window}];
        if (std::find(actions.begin(), actions.end(), action) == actions.end())
            actions.push_back(action);
        auto& sources = origins[{state, window}];
        if (std::none_of(sources.begin(), sources.end(), [&](const auto& origin) {
            return origin.action == action && origin.item == core;
        })) sources.push_back(conflictOrigin(action, core));
    };

    for (std::size_t state = 0; state < canonical_item_set.size(); ++state) {
        for (const auto& [symbol, target] : transitions[state]) {
            if (isNonterminal(symbol)) goto_table[state][symbol] = target;
        }
        for (const auto& proposal : proposalsForState(state))
            propose(state, proposal.window, proposal.action, proposal.item);
    }
    for (const auto& [cell, actions] : proposals) {
        if (actions.size() == 1) {
            k_action_table[cell.first][cell.second] = actions.front();
            if (k == 1) action_table[cell.first][cell.second.front()] = actions.front();
        } else {
            conflicts.push_back(Conflict{cell.first, cell.second.front(), actions, cell.second, origins.at(cell)});
        }
    }
}

void LRParser::build() {
    buildCanonical();
    buildTables();
}

auto LRParser::conflictOrigin(Action action, const LR0Core& core) const -> ConflictOrigin {
    const auto& p = productions.at(core.production);
    ConflictOrigin origin;
    origin.action = action;
    origin.item = core;
    origin.rule = p.source.original_rules.empty() ? p.lhs : p.source.original_rules;
    origin.at_end = core.dot_pos == p.rhs.size();
    origin.member = core.dot_pos < p.source_members.size() ? p.source_members[core.dot_pos] : p.source_members.size() + 1;
    origin.position = p.source.position;
    if (!p.source.rule_members.empty()) {
        const auto index = std::min(core.dot_pos, p.source.rule_members.size() - 1);
        if (p.source.rule_members[index]->position.line)
            origin.position = p.source.rule_members[index]->position;
    }
    // Generated group/quantifier productions retain their owner's name. Locate
    // the original member by its source span rather than showing a helper index.
    if (tree->contains(origin.rule)) {
        const auto& rule = tree->getTreeMap().at(origin.rule);
        if (!origin.position.line) origin.position = rule.position;
        // Helper names encode the member they were created from. This also
        // supplies an origin when an epsilon helper has no positioned member.
        if (p.lhs.size() > origin.rule.size()) {
            const auto& helper = p.lhs[origin.rule.size()];
            auto digit = helper.find_first_of("0123456789");
            if (digit != std::string::npos) {
                const auto source_index = std::stoull(helper.substr(digit));
                if (source_index < rule.rule_members.size()) {
                    origin.member = 0;
                    for (std::size_t i = 0; i <= source_index; ++i) {
                        const auto& member = rule.rule_members[i];
                        if (!(member->isAutoGenerated && member->isName() && member->getName().name == constants::whitespace))
                            ++origin.member;
                    }
                    origin.position = rule.rule_members[source_index]->position;
                    if (origin.position.file.empty()) origin.position.file = rule.position.file;
                }
            }
        }
        std::size_t index = 0;
        for (const auto& member : rule.rule_members) {
            if (member->isAutoGenerated && member->isName() && member->getName().name == constants::whitespace) continue;
            ++index;
            if (member->position.line && origin.position.offset >= member->position.offset &&
                origin.position.offset < member->position.offset + member->position.length) {
                origin.member = index;
                break;
            }
        }
    }
    return origin;
}

auto LRParser::formatConflict(const Conflict& c) const -> std::string {
    std::ostringstream out;
    out << "LR parser conflict in state " << c.state << " on [" << formatSequence(c.lookahead_sequence)
        << "] (" << c.actions.size() << " different actions)";
    for (const auto& origin : c.origins) {
        out << "\n  " << ActionTypeToString(origin.action.type) << ": rule '" << formatName(origin.rule)
            << "', member " << origin.member;
        if (origin.at_end) out << " (end of production)";
        if (!origin.position.file.empty() || origin.position.line) {
            out << " at " << (origin.position.file.empty() ? "<grammar>" : origin.position.file);
            if (origin.position.line) out << ":" << origin.position.line << ":" << origin.position.column;
        }
        out << "\n    " << formatItem(origin.item, canonical_item_set.at(c.state).at(origin.item), productions);
    }
    return out.str();
}

void LRParser::requireConflictFree() const {
    if (conflicts.empty()) return;
    std::ostringstream report;
    for (std::size_t i = 0; i < conflicts.size(); ++i) {
        if (i) report << "\n";
        report << formatConflict(conflicts[i]);
    }
    throw std::runtime_error(report.str());
}

const LRParser::ActionTable& LRParser::getActionTable() const {
    if (k != 1) throw std::logic_error("LR(k): use getKActionTable() when k > 1");
    return action_table;
}

stdu::vector<std::map<LRParser::Lookahead, LRParser::Action>>
LRParser::getKActionTableAsRow() const {
    stdu::vector<std::map<Lookahead, Action>> rows(canonical_item_set.size());
    for (const auto& [state, row] : k_action_table) rows.at(state) = row;
    return rows;
}

stdu::vector<utype::unordered_map<LRParser::Name, LRParser::Action>>
LRParser::getActionTableAsRow() const {
    if (k != 1) throw std::logic_error("LR(k): use getKActionTableAsRow() when k > 1");
    stdu::vector<utype::unordered_map<Name, Action>> rows(canonical_item_set.size());
    for (const auto& [state, row] : action_table) rows.at(state) = row;
    return rows;
}

stdu::vector<utype::unordered_map<LRParser::Name, std::size_t>>
LRParser::getGotoTableAsRow() const {
    stdu::vector<utype::unordered_map<Name, std::size_t>> rows(canonical_item_set.size());
    for (const auto& [state, row] : goto_table) rows.at(state) = row;
    return rows;
}

std::size_t LRParser::getMaxStatesCount() const {
    return canonical_item_set.empty() ? 0 : canonical_item_set.size() - 1;
}

std::string LRParser::formatItem(const LR0Core& core, const Lookaheads& lookaheads,
                                 const std::vector<Production>& productions) {
    const auto& p = productions.at(core.production);
    std::ostringstream out;
    out << formatName(p.lhs) << " ->";
    for (std::size_t i = 0; i <= p.rhs.size(); ++i) {
        if (i == core.dot_pos) out << " .";
        if (i < p.rhs.size()) out << " " << formatName(p.rhs[i]);
    }
    out << " , {";
    bool first_item = true;
    for (const auto& token : lookaheads) {
        if (!first_item) out << ", ";
        first_item = false;
        out << formatSequence(token);
    }
    return out.str() + "}";
}

void LRParser::printCanonicalCollection(const std::string& filename) const {
    std::ofstream file(filename);
    if (!file) throw std::runtime_error("Cannot write LR item collection: " + filename);
    for (std::size_t state = 0; state < canonical_item_set.size(); ++state) {
        file << "I" << state << ":\n";
        for (const auto& [core, la] : canonical_item_set[state])
            file << "  " << formatItem(core, la, productions) << "\n";
    }
}

void LRParser::printTables(const std::string& filename) const {
    std::ofstream file(filename);
    if (!file) throw std::runtime_error("Cannot write LR tables: " + filename);
    file << "Productions (REDUCE index):\n";
    for (std::size_t id = 1; id < productions.size(); ++id) {
        const auto& p = productions[id];
        file << "  " << id - 1 << ": " << formatName(p.lhs) << " ->";
        for (const auto& s : p.rhs) file << " " << formatName(s);
        if (p.rhs.empty()) file << " epsilon";
        file << "\n";
    }
    file << "ACTION (k=" << k << "):\n";
    for (std::size_t state = 0; state < canonical_item_set.size(); ++state) {
        if (auto row = k_action_table.find(state); row != k_action_table.end()) {
            std::map<Lookahead, Action> sorted(row->second.begin(), row->second.end());
            for (const auto& [symbol, action] : sorted)
                file << "  " << state << " [" << formatSequence(symbol) << "] "
                     << ActionTypeToString(action.type) << " " << action.state << "\n";
        }
    }
    file << "GOTO:\n";
    for (std::size_t state = 0; state < canonical_item_set.size(); ++state) {
        if (auto row = goto_table.find(state); row != goto_table.end()) {
            std::map<Name, std::size_t> sorted(row->second.begin(), row->second.end());
            for (const auto& [symbol, target] : sorted)
                file << "  " << state << " " << formatName(symbol) << " " << target << "\n";
        }
    }
    file << "CONFLICTS:\n";
    for (const auto& c : conflicts) file << formatConflict(c) << "\n";
    if (auto_conflicts) {
        file << "AUTOMATIC RESOLUTIONS:\n";
        for (const auto& resolution : resolutions) {
            const auto& conflict = conflicts.at(resolution.conflict);
            file << "  state " << conflict.state << " on [" << formatSequence(conflict.lookahead_sequence) << "]: ";
            if (!resolution.lookahead) file << "runtime branching\n";
            else {
                file << "lookahead " << resolution.lookahead << "\n";
                for (const auto& decision : resolution.decisions)
                    file << "    [" << formatSequence(decision.window) << "] " << ActionTypeToString(decision.action.type)
                         << " " << decision.action.state << "\n";
            }
        }
    }
}
